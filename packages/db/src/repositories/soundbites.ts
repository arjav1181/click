import { and, asc, desc, eq, sql } from "drizzle-orm";
import { withTenant, type TenantContext } from "../client";
import { soundbites } from "../schema";

export interface SoundbiteRow {
  id: string;
  meetingId: string;
  meetingTitle: string;
  startMs: number;
  endMs: number;
  title: string | null;
  storageKey: string | null;
  autoGenerated: boolean;
  createdAt: string;
}

export async function listSoundbites(ctx: TenantContext): Promise<SoundbiteRow[]> {
  return withTenant(ctx, async (tx) => {
    const rows = await tx
      .select({
        id: soundbites.id,
        meetingId: soundbites.meetingId,
        meetingTitle: sql<string>`coalesce((select m.title from meetings m where m.id = ${soundbites.meetingId}), 'Meeting')`,
        startMs: soundbites.startMs,
        endMs: soundbites.endMs,
        title: soundbites.title,
        storageKey: soundbites.storageKey,
        autoGenerated: soundbites.autoGenerated,
        createdAt: soundbites.createdAt,
      })
      .from(soundbites)
      .where(eq(soundbites.orgId, ctx.orgId))
      .orderBy(desc(soundbites.createdAt));
    return rows.map((row) => ({
      id: row.id,
      meetingId: row.meetingId,
      meetingTitle: row.meetingTitle,
      startMs: row.startMs,
      endMs: row.endMs,
      title: row.title,
      storageKey: row.storageKey,
      autoGenerated: row.autoGenerated,
      createdAt: row.createdAt.toISOString(),
    }));
  });
}

export async function createSoundbite(
  ctx: TenantContext,
  input: { meetingId: string; startMs: number; endMs: number; title?: string },
): Promise<{ id: string }> {
  return withTenant(ctx, async (tx) => {
    const rows = await tx
      .insert(soundbites)
      .values({
        orgId: ctx.orgId,
        meetingId: input.meetingId,
        createdBy: ctx.userId,
        startMs: input.startMs,
        endMs: input.endMs,
        title: input.title?.slice(0, 200) ?? null,
      })
      .returning({ id: soundbites.id });
    return { id: rows[0].id };
  });
}

export async function deleteSoundbite(ctx: TenantContext, id: string): Promise<{ ok: boolean }> {
  return withTenant(ctx, async (tx) => {
    const rows = await tx
      .delete(soundbites)
      .where(and(eq(soundbites.id, id), eq(soundbites.orgId, ctx.orgId)))
      .returning({ id: soundbites.id });
    return { ok: rows.length > 0 };
  });
}
