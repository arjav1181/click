#!/usr/bin/env node
// Generates the CSS custom properties consumed by packages/ui from the
// canonical token files in replica/design. Edit the JSON, run `pnpm tokens`.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const designDir = resolve(root, "replica/design");
const outDir = resolve(root, "packages/ui/src/styles");

const light = JSON.parse(await readFile(resolve(designDir, "tokens.json"), "utf8"));
const dark = JSON.parse(await readFile(resolve(designDir, "tokens.dark.json"), "utf8"));

const vars = (tok) => {
  const out = [];
  for (const [k, v] of Object.entries(tok.color)) out.push(`  --color-${k}: ${v};`);
  for (const [k, v] of Object.entries(tok.font)) out.push(`  --font-${k}: ${v};`);
  for (const [k, v] of Object.entries(tok.type)) {
    out.push(`  --text-${k}-size: ${v.size}px;`);
    out.push(`  --text-${k}-line: ${v.line}px;`);
    out.push(`  --text-${k}-weight: ${v.weight};`);
  }
  out.push(`  --space: ${tok.space[1]}px;`);
  tok.space.forEach((v, i) => out.push(`  --space-${i}: ${v}px;`));
  for (const [k, v] of Object.entries(tok.radius)) {
    out.push(`  --radius-${k}: ${typeof v === "number" ? `${v}px` : v};`);
  }
  for (const [k, v] of Object.entries(tok.shadow)) out.push(`  --shadow-${k}: ${v};`);
  for (const [k, v] of Object.entries(tok.motion)) out.push(`  --motion-${k}: ${v};`);
  for (const [k, v] of Object.entries(tok.layout)) out.push(`  --layout-${k}: ${v}px;`);
  return out.join("\n");
};

const css = `/* Generated by scripts/build-tokens.mjs — do not edit by hand.
   Source: replica/design/tokens.json, replica/design/tokens.dark.json */

:root {
${vars(light)}
}

[data-theme="dark"] {
${vars(dark)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(dark)}
  }
}
`;

await mkdir(outDir, { recursive: true });
await writeFile(resolve(outDir, "tokens.css"), css);
console.log("wrote packages/ui/src/styles/tokens.css");
