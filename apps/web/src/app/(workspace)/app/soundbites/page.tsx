"use client";

import { useCallback, useEffect, useState } from "react";
import {
  Badge,
  Banner,
  Button,
  Card,
  CardHeader,
  EmptyState,
  Skeleton,
  useToast,
} from "@click/ui";
import { deleteSoundbite, fetchSoundbites, type SoundbiteRow } from "@/lib/api";

function formatTime(ms: number) {
  const seconds = Math.floor(ms / 1000);
  return `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, "0")}`;
}

export default function SoundbitesPage() {
  const toast = useToast();
  const [soundbites, setSoundbites] = useState<SoundbiteRow[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const load = useCallback(async () => {
    setLoading(true);
    setError(null);
    const result = await fetchSoundbites();
    if (result.data) setSoundbites(result.data.soundbites);
    if (result.error) setError(result.error);
    setLoading(false);
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  const remove = async (id: string) => {
    const result = await deleteSoundbite(id);
    if (result.error) {
      toast.push({ tone: "error", title: "Soundbite could not be deleted", description: result.error });
      return;
    }
    await load();
  };

  return (
    <div className="mx-auto max-w-5xl p-6">
      <div className="mb-4">
        <h2 className="text-xl font-semibold text-text">Soundbites</h2>
        <p className="text-sm text-text-muted">
          Clips from your meetings. Create them from the transcript tab of a meeting.
        </p>
      </div>

      {error ? (
        <Banner
          tone="danger"
          title="Soundbites could not be loaded"
          className="mb-4"
          action={
            <Button variant="secondary" size="sm" onClick={load}>
              Retry
            </Button>
          }
        >
          {error}
        </Banner>
      ) : null}

      {loading ? (
        <div className="grid gap-3">
          <Skeleton className="h-20" rounded="lg" />
          <Skeleton className="h-20" rounded="lg" />
        </div>
      ) : soundbites.length === 0 ? (
        <Card>
          <EmptyState
            title="No soundbites yet"
            description="Clip a moment from a meeting's transcript to create a soundbite."
          />
        </Card>
      ) : (
        <div className="grid gap-3">
          {soundbites.map((clip) => (
            <Card key={clip.id} className="p-4">
              <div className="flex flex-wrap items-center justify-between gap-3">
                <div className="min-w-0">
                  <p className="text-sm font-semibold text-text">
                    {clip.title || "Untitled clip"}
                  </p>
                  <p className="text-xs text-text-muted">
                    {clip.meetingTitle} · {formatTime(clip.startMs)} – {formatTime(clip.endMs)}
                  </p>
                </div>
                <div className="flex items-center gap-2">
                  {clip.autoGenerated ? <Badge tone="accent">Auto</Badge> : null}
                  <Button variant="danger" size="sm" onClick={() => void remove(clip.id)}>
                    Delete
                  </Button>
                </div>
              </div>
            </Card>
          ))}
        </div>
      )}
    </div>
  );
}
